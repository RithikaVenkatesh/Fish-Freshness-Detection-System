def predict_image(image):

    img = cv2.resize(image,(224,224))
    img = np.expand_dims(img, axis=0)
    img = preprocess_input(img)

    pred = model.predict(img)[0][0]

    if pred > 0.5:
        label = "🛑 Spoiled Fish"
        confidence = pred
    else:
        label = "✅ Fresh Fish"
        confidence = 1 - pred

    return label, f"{confidence*100:.2f}%"



