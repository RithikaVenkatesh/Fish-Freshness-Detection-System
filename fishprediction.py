import os

os.makedirs("dataset/train/Fresh", exist_ok=True)
os.makedirs("dataset/train/Spoiled", exist_ok=True)

os.makedirs("dataset/test/Fresh", exist_ok=True)
os.makedirs("dataset/test/Spoiled", exist_ok=True)

print("2-class folder structure created!")

from tensorflow.keras.applications import MobileNetV2

base_model = MobileNetV2(
    weights="imagenet",
    include_top=False,
    input_shape=(224, 224, 3)
)

base_model.trainable = True

for layer in base_model.layers[:-30]:
    layer.trainable = False


print("MobileNetV2 loaded and frozen ✅")

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.optimizers import Adam

base_model.trainable = False  # Freeze first

model = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    Dense(128, activation="relu"),
    Dropout(0.5),
    Dense(1, activation="sigmoid")
])

model.compile(
    optimizer=Adam(learning_rate=1e-3),
    loss="binary_crossentropy",
    metrics=["accuracy"]
)

model.summary()

import os, random, shutil

def split_data(src, dst, ratio=0.75):
    files = os.listdir(src)
    random.shuffle(files)

    split = int(len(files) * ratio)
    test_files = files[split:]

    for f in test_files:
        shutil.move(
            os.path.join(src, f),
            os.path.join(dst, f)
        )

# 🔥 CALL THE FUNCTION OUTSIDE
split_data("dataset/train/Fresh", "dataset/test/Fresh")
split_data("dataset/train/Spoiled", "dataset/test/Spoiled")

print("Train–Test split completed ✅")

